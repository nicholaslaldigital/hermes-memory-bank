"""Generate the two Hermes-hosted copies of the network view from ui/engine.js:

    dashboard/dist/index.js   - web dashboard tab (classic script, React from the SDK)
    desktop/plugin.js         - desktop app page (single ESM file, SDK imports only)

Both hosts load one self-contained file, so the engine is inlined. Run after
editing engine.js:   python ui/build.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARK = "/*__ENGINE__*/"
BANNER = "/* Generated by ui/build.py from ui/engine.js - edit that file, not this one. */\n"

DASHBOARD = BANNER + """(function () {
  'use strict';
  var SDK = window.__HERMES_PLUGIN_SDK__;
  if (!SDK || !window.__HERMES_PLUGINS__) return;
  var React = SDK.React;
  var NAME = 'memorybank';

/*__ENGINE__*/

  function api(path, options) {
    options = options || {};
    var init = { method: options.method || 'GET' };
    if (options.body) {
      init.headers = { 'Content-Type': 'application/json' };
      init.body = JSON.stringify(options.body);
    }
    return SDK.fetchJSON('/api/plugins/' + NAME + path, init);
  }

  function MemoryBankPage() {
    var ref = React.useRef(null);
    React.useEffect(function () {
      var graph = createMemoryGraph(ref.current, { fetchJSON: api });
      return function () { graph.destroy(); };
    }, []);
    return React.createElement('div', {
      ref: ref,
      style: { position: 'relative', width: '100%', height: 'calc(100vh - 140px)', minHeight: '460px' }
    });
  }

  window.__HERMES_PLUGINS__.register(NAME, MemoryBankPage);
})();
"""

DESKTOP = BANNER + """/**
 * Memory Bank - desktop page: a live network view of everything Hermes
 * remembers. Ships inside the `memorybank` plugin folder as desktop/plugin.js;
 * the app copies it to desktop-plugins/memorybank/ and lists it under
 * Capabilities > Plugins (off until you switch it on). Data comes from the
 * plugin's own backend (dashboard/plugin_api.py) through ctx.rest.
 */
import { PALETTE_AREA, ROUTES_AREA, SIDEBAR_NAV_AREA, host } from '@hermes/plugin-sdk'
import { useEffect, useRef } from 'react'
import { jsx } from 'react/jsx-runtime'

/*__ENGINE__*/

const ID = 'memorybank'
const PATH = '/memory-bank'

export default {
  id: ID,
  name: 'Memory Bank',
  description: 'Live network view of Hermes\\' long-term memory: memories, people and systems, skills and past sessions.',
  register(ctx) {
    const open = new Set()

    function MemoryBankPage() {
      const ref = useRef(null)
      useEffect(() => {
        const graph = createMemoryGraph(ref.current, {
          fetchJSON: (path, options) =>
            ctx.rest(path, options && options.method ? { method: options.method, body: options.body } : undefined)
        })
        open.add(graph)
        return () => {
          open.delete(graph)
          graph.destroy()
        }
      }, [])
      return jsx('div', {
        ref,
        className: 'h-full w-full',
        style: { position: 'relative', width: '100%', height: '100%', minHeight: '420px' }
      })
    }

    // Hermes pushes this whenever the bank recalls or learns something.
    ctx.onEvent('plugin.memorybank.changed', () => {
      open.forEach(graph => graph.sync())
    })
    ctx.onDispose(() => {
      open.forEach(graph => graph.destroy())
      open.clear()
    })

    ctx.registerMany([
      {
        id: 'page',
        area: ROUTES_AREA,
        data: { path: PATH },
        render: () => jsx(MemoryBankPage, {})
      },
      {
        id: 'nav',
        area: SIDEBAR_NAV_AREA,
        order: 60,
        data: { path: PATH, label: 'Memory Bank', codicon: 'type-hierarchy' }
      },
      {
        id: 'open',
        area: PALETTE_AREA,
        data: {
          id: 'memorybank.open',
          label: 'Open Memory Bank',
          keywords: ['memory', 'bank', 'graph', 'network', 'recall', 'brain'],
          run: () => host.navigate(PATH)
        }
      }
    ])
  }
}
"""


def _indent(source: str, spaces: int) -> str:
    pad = " " * spaces
    return "\n".join((pad + line) if line.strip() else line for line in source.splitlines())


def targets() -> dict:
    engine = (ROOT / "ui" / "engine.js").read_text(encoding="utf-8").rstrip() + "\n"
    return {
        ROOT / "dashboard" / "dist" / "index.js": DASHBOARD.replace(MARK, _indent(engine, 2)),
        ROOT / "desktop" / "plugin.js": DESKTOP.replace(MARK, engine),
    }


def build(check: bool = False) -> int:
    """Write both bundles; with ``check`` write nothing and fail if either is out of date."""
    stale = 0
    for path, text in targets().items():
        if check:
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != text:
                stale += 1
                print(f"out of date: {path.relative_to(ROOT)} - run: python ui/build.py")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))   # LF line ends on every system; write_text(newline=) needs Python 3.10
        print(f"wrote {path.relative_to(ROOT)}  ({len(text) / 1024:.1f} KB)")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(build(check="--check" in sys.argv[1:]))
